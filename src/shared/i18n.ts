export type Idioma = 'en' | 'es'
export interface InfoIdioma {
  idioma: Idioma
  locale: string // para fechas: «en-US», «es-ES», «en-GB»…
}

export const textos = (i: Idioma): Textos => (i === 'es' ? es : en)

/**
 * El idioma del sistema (CAUCE_LANG=en|es lo fuerza; si no, LC_ALL > LC_MESSAGES > LANG). Español si
 * el sistema está en español; para todo lo demás, inglés.
 */
export function idiomaDelSistema(env: Record<string, string | undefined>): InfoIdioma {
  const forzado = env.CAUCE_LANG
  const sistema = [env.LC_ALL, env.LC_MESSAGES, env.LANG]
    .map((v) => v?.split(/[.@]/)[0]?.replace('_', '-'))
    .find((v) => v && /^[a-z]{2,3}(-[A-Za-z0-9]+)?$/i.test(v))
  const idioma: Idioma = forzado === 'es' || forzado === 'en' ? forzado : sistema?.toLowerCase().startsWith('es') ? 'es' : 'en'
  // El locale del sistema si es del mismo idioma (en-GB, es-MX…), para respetar sus costumbres.
  const locale = sistema?.toLowerCase().startsWith(idioma) ? sistema : idioma === 'es' ? 'es-ES' : 'en-US'
  return { idioma, locale }
}
